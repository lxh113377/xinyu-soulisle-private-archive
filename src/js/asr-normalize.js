/* 心屿 · 语音转写归一化（r174 / A2）
 *
 * 为什么有这件（一手来源，不是拍脑袋）：A1 回放台架 `_test/asr_replay_check.py` 的
 * scene-noise-mixed 样本实测坐实 —— `pickBest`（voice-call.js）**压根没有任何剔除口头语的机制**，
 * 引擎把「嗯那个我今天有点崩溃了」整句送进来，它就整句转给用户。本模块补这一级。
 *
 * 分级设计（关键，别合并）：
 *   选候选 = pickBest（**不改写文本**，保住 A1 的 E1b 零改写不变量）
 *   清洗文本 = 本模块 normalize（在 pickBest 之后单独一级，改写是显式的、可单测的）
 * 两者合成才进对话。合成后必须仍等于「某条候选经同一清洗」——来源可追，不许凭空造字。
 *
 * 🔴 设计红线一：**禁动带语义的词**。「有点累」≠「累」、「说一下」≠「说」——
 *   删掉程度词会改变语义，所以「有点/有点儿/有些/一点/一下」一律【不在表内】。
 * 🔴 设计红线二：清洗到空必须回退原文。「嗯」不能变成空串（那会让收句判据拿到空文本）。
 * 🔴 设计红线三（r174 实测后立，**推翻了我自己的初版**）：**句末语气词一律不许剥**。
 *   初版把「呀/啊/吧/呢」当噪声剥掉，E5 门槛当场判红并给出证据：cmn-01/04/05 三条
 *   「今天还行呀」→「今天还行」，CER 从 0.000 恶化到 0.200。
 *   原理：**句首口头语是非语义噪声，句末语气词是用户真说出来的语气** —— 情感陪伴场景里
 *   语气本身是信息（"还行呀" 与 "还行" 不是一回事），剥它是拿 fidelity 换整洁。
 *   故 `stripTrailingParticles` 保留函数但**默认不接线**，E6 有专门一条腿钉住「不许剥」。
 *
 * 判据：`_test/asr_replay_check.py`（expect_norm 腿 + E5 增益腿 + E6 纯函数组）；
 * 该件同时钉「清洗后文本 == 某条候选的清洗结果」，不许凭空造字。
 */
window.ASRNormalize = (function () {
  // 句首口头语：按长度降序匹配，否则「那个」会被「那」之类的短词先咬掉一半
  const LEAD = ["怎么说呢", "我跟你说", "你知道吗", "那个", "这个", "就是", "然后", "反正",
                "其实", "嗯", "呃", "唔", "啊", "哦"].sort((a, b) => b.length - a.length);
  // 句末语气词：单字，只在剥掉后仍有内容时才剥
  const TAIL = "啊呀吧呢哦嘛啦嘞咯喽";
  const MIN_KEEP = 2;      // 剥到比这更短就停手，避免把整句洗没
  const WS = /\s+/g;

  /** 只剥句首口头语，可剥多轮（"嗯那个呃我今天…" 要连着剥三层） */
  function stripLeadingFillers(t) {
    let s = String(t || "").trim(), moved = true;
    while (moved && s.length > MIN_KEEP) {
      moved = false;
      for (const f of LEAD) {
        if (s.length - f.length >= MIN_KEEP && s.indexOf(f) === 0) { s = s.slice(f.length).trim(); moved = true; break; }
      }
    }
    return s;
  }

  /** 剥句末语气字。🔴 **默认不接线**（红线三）：保留函数是因为可测、可复用，
   *  以及留一条「哪天要剥必须先过 E5」的显式开关位 —— 不是留着随时调用的私货。
   *  真要启用时先改 E5 阈值口径，并同步改 norm-02/norm-03 两条样本的期望。 */
  function stripTrailingParticles(t) {
    let s = String(t || "").trim(), moved = true;
    while (moved && s.length > MIN_KEEP) {
      const last = s.charAt(s.length - 1);
      if (TAIL.indexOf(last) < 0 || s.length - 1 < MIN_KEEP) break;
      s = s.slice(0, -1).trim(); moved = true;
    }
    return s;
  }

  /* ── 断句碎片前置过滤（r175 / A3-1）───────────────────────────────
   * 真实缺口（一手定位，不是拍脑袋）：`voice-call.js` 的 onresult 把引擎连续投递的片段
   * 直接 `said += t` 拼起来。Web Speech 在 continuous 模式**重连/补投**时会给出
   * 【全等重复】或【互相包含】的片段（「我今天有点崩溃」→ 补投「我今天有点崩溃了」），
   * 直接拼 ⇒ 「我今天有点崩溃我今天有点崩溃了」—— 整句重复进对话，下游模型拿到的是错的话。
   *
   * 🔴 红线四：**只去「全等重复」与「包含」，绝不做局部重叠合并**。
   *   「我今天有点崩溃了」+「崩溃了吗」这类后缀/前缀局部重叠，**可能是用户真说的**
   *   （自我修正、结巴、强调）。把它合并 = 拿 fidelity 换整洁 —— 与红线三同族，不许做。
   * 🔴 红线五：无重复、无包含时，输出必须 == 逐段 normalize 后直接拼接（**零改写不变量**）。
   *   这条是接线不回归的唯一保障，E7 有专门腿钉住。
   * 🔴 红线六：本函数是**唯一的 normalize 调用点** —— 生产路径必须喂【未经清洗的原文】。
   *   喂进去再洗一遍不幂等（「那个我今天」洗两次会变成「我今天」），那属于偷偷改语义。
   */
  function mergeFragments(parts) {
    const out = [];
    (Array.isArray(parts) ? parts : [parts]).forEach((p) => {
      const t = normalize(p);
      if (!t) return;                                   // 空片段不进拼接（原路径 += 空串也是空）
      if (!out.length) { out.push(t); return; }
      const last = out[out.length - 1];
      if (t === last) return;                           // 全等重复：后一条是补投，丢
      if (t.indexOf(last) === 0) { out[out.length - 1] = t; return; }        // 后段 = 前段 + 续写 ⇒ 取长
      if (last.indexOf(t) === 0) return;                // 后段是前段的前缀 ⇒ 信息已含在前段里，丢
      if (t.indexOf(last) >= 0) { out[out.length - 1] = t; return; }        // 后段整体含前段 ⇒ 取长
      if (last.indexOf(t) >= 0) return;                 // 前段整体含后段 ⇒ 保留前段，丢后段
      out.push(t);
    });
    return out.join("");
  }

  /* ── 方言形态层（r176 / A4）─────────────────────────────────────────
   * 需求②「适配方言特有的俚语词汇、优化声学模型和语言模型的匹配逻辑」在本仓架构下的
   * **唯一可落地形态**：引擎是浏览器 Web Speech，它的声学模型/语言模型我们一行都碰不到；
   * 我们真正拥有的只有 n-best 重排（voice-call.js 的 altScore）。所以「语言模型匹配」的
   * 等价物就是 —— **让方言说法也能被情绪词表认出来**，不再被通用模型的谐音错字靠置信度压过。
   *
   * 真实缺口（一手，不是拍脑袋）：粤语「我好攰」的「攰」不在词表里 ⇒ altScore 词表命中=0，
   * 于是引擎给的谐音错字「我好贵」（conf 0.9）轻松赢过用户真说的话（conf 0.3）。
   * 方言用户在这个产品里是**系统性吃亏**的：不是引擎听错了，是我们的重排不认他的话。
   *
   * 🔴 红线七：**只用于候选打分，绝不改写文本**。方言说法是用户真说的话，把它改成普通话
   *   = 拿 fidelity 换整洁（与红线三同族）。本表不得进 normalize、不得进 mergeFragments。
   * 🔴 红线八：**映射目标必须真在词表里**才算命中。否则方言表会退化成「含方言字就加分」，
   *   那等于没判 —— 而且 E9-3 有专门一条腿钉住它（造不出分的映射必须当场现形）。
   * 🔴 红线九：方言命中的权重**必须低于**词表直接命中（+1.0 < +1.5）。理由不是保守：
   *   词表直接命中是**强证据**（人说「失眠」就是失眠），方言映射是**人工表的间接证据**
   *   （我把「攰」映射成「累」是我的判断，可能不准）。弱证据不得压过强证据，E9-4 腿钉序。
   * ⚠ 收词纪律（本表最易出错处）：**只收方言专属形态**（普通话不这么用的字/词）。
   *   「喊」（粤语=哭 / 普通话=叫）、「好」（粤语=很 / 普通话=好）、「老」（东北=很 / 普=年长）
   *   这类**同形歧义词一律不收** —— 收了就会给普通话句子乱加分，那是拿准确率换假召回。
   * ⚠ 诚实边界：本表是**人工编纂的小表**（30 条），不是从方言语料学出来的。
   *   它的作用是「把方言从 0 分抬到有分」，**不构成方言识别准确率的证据**。
   * ⚠ 目标词必须**真在 SSOT 词表里**（且长度≥2 —— altScore 只认 len>=2）：编纂时逐条核过，
   *   「痛苦/委屈/喜欢/郁闷/不舍/累(单字)」这 6 个候选目标**实测不在词表**，已改用真实存在的词
   *   （累→疲惫、痛苦→难受、委屈→难受、郁闷→抑郁、不舍→舍不得、稀罕 整条删除）。
   *   漏核的后果不是报错而是**静默 0 分**（映射永不命中），这类错只能靠 E9-3 腿现形。
   * ⚠ 本表实为「方言 + 地域口语形态」表：「恼火/闹心/憋屈/心塞/不得劲」在北方普通话口语里也用，
   *   收录的理由是它们**确实携带情绪且词表不收**，不是因为它们只属于某一方言区。
   */
  // 方言形态 → 普通话同义（后者必须命中真实词表才算数，见红线八）
  const DIALECT = [
    // 粤语
    ["攰", "疲惫"], ["忟", "烦躁"], ["嬲", "生气"], ["唔开心", "难过"], ["唔舒服", "难受"],
    ["心噏", "难受"], ["好惊", "害怕"], ["冇心机", "低落"], ["瞓唔着", "睡不着"],
    // 四川话
    ["巴适", "舒服"], ["不巴适", "难受"], ["恼火", "难受"], ["心焦", "焦虑"], ["焦人", "焦虑"],
    ["造孽", "难受"], ["莫得劲", "疲惫"],
    // 东北话
    ["闹心", "烦躁"], ["憋屈", "难受"], ["不得劲", "难受"], ["不得劲儿", "难受"],
    ["心塞", "难受"], ["闹挺", "烦躁"],
    // 上海话（吴语）
    ["懊糟", "烦躁"], ["勿适意", "难受"], ["触气", "生气"], ["勿开心", "难过"],
    // 闽南语（台语，含繁体形态 —— 引擎在 zh-HK/zh-TW 语境下会吐繁体）
    ["艱苦", "难受"], ["鬱卒", "抑郁"], ["毋甘", "舍不得"], ["毋爽", "难受"], ["驚惶", "害怕"]
  ].sort((a, b) => b[0].length - a[0].length);
  // 红线十一用：方言形态前紧邻这些字 ⇒ 语义反转，不计分（与词表 neg 同源，但方言层只看**紧邻前一字**，
  // 不做整句否定传播 —— 那是 EmotionEngine 的活，这里越权会两头都算错）
  const NEG_BEFORE = "不没冇勿毋唔無弗";

  /* 词表集合缓存：altScore 每次都会调，逐候选重建 Set 是浪费；
     用「LEX 引用是否变了」判断失效（词表是常驻对象，换掉才重算） */
  let _lexRef = null, _lexSet = null;
  function lexSet() {
    const E = window.EmotionEngine;
    const L = E && E.LEX;
    if (!L) return null;
    if (_lexRef !== L) {
      const s = new Set();
      for (const k in L) {
        const v = L[k], ws = Array.isArray(v) ? v : (v || {}).words;
        if (!ws) continue;
        for (const w of ws) if (w && w.length >= 2) s.add(w);
      }
      _lexRef = L; _lexSet = s;
    }
    return _lexSet;
  }

  /** 文本里命中了几条方言形态（**仅供打分**，绝不改写文本 —— 红线七）
   *
   * 🔴 红线十：**目标词已直接出现在文本里时不计方言分**（防双计）。「巴适得很烦躁」这种
   *   既含方言词又含词表词的句子，词表层已经给了 +1.5，方言层再给 +1.0 就是同一份证据算两次，
   *   会当场掀翻红线九的序关系（弱证据反而总分更高）。E9-5 腿钉住。 */
  function dialectHits(t) {
    const s = String(t || ""), lex = lexSet();
    if (!s || !lex) return 0;
    let n = 0;
    for (const pair of DIALECT) {
      const i = s.indexOf(pair[0]);
      if (i < 0) continue;
      // 🔴 红线十一：否定前缀不得计分。「不巴适」里也含「巴适」，但语义是**反的**
      //   （巴适=舒服 / 不巴适=难受）—— 按子串加分会把否定句加成正面情绪，这比漏识别更糟。
      //   显式收录的否定式（不巴适/唔开心/勿开心/勿适意/毋爽）**自带**否定字作词首，
      //   故它的起始前一字符不是否定字 ⇒ 不被本规则误伤，仍正常计分。E9 有两条腿钉住这对关系。
      if (i > 0 && NEG_BEFORE.indexOf(s.charAt(i - 1)) >= 0) continue;
      if (s.indexOf(pair[1]) < 0 && lex.has(pair[1]) && n < 4) n++;   // 红线八 + 红线十
    }
    return n;
  }

  /** 归一化主入口：压空白 → 剥【句首】口头语 → 兜底回退。
   *  **只动句首、只动空白，不动句末语气、不改字序、不删实词**（红线一 + 红线三）。 */
  function normalize(t) {
    const raw = String(t || "").trim().replace(WS, " ");
    if (!raw) return "";
    const out = stripLeadingFillers(raw);
    return out || raw;          // 红线二：洗没了就交还原文，绝不交空串
  }

  return {
    normalize,
    mergeFragments,
    dialectHits,                     // 只打分不改写（红线七），接线在 voice-call.js 的 altScore
    stripLeadingFillers,
    stripTrailingParticles,          // 🔴 默认不接线，见函数头「红线三」
    /** 供判据读取，不参与业务路径 */
    _unit: { normalize, mergeFragments, dialectHits, lexSet, DIALECT,
      stripLeadingFillers, stripTrailingParticles, MIN_KEEP }
  };
})();
